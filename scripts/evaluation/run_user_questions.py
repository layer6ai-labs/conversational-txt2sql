"""
Run agentic main.run for each user_query in a .jsonl and collect results.
Input is expected to have at least these fields:
- instance_id: unique ID for the query
- selected_database: name of the database to use (informational only)
- user_query: the natural language question to run

Output is a .jsonl with these fields:
- instance_id: copied from input
- selected_database: copied from input
- user_query: copied from input
- generated_sql: the first SQL statement generated by the crew (or None)
- rows_returned: list of records returned by executing the SQL (or None)
- error: any error message encountered (or None)
- elapsed_seconds: time taken to run the query (float, or None)

Command-line usage:

uv run python evaluation/run_user_questions.py --input "data/labelled_sets/labelled_set_processed.jsonl" --output "data/labelled_sets/labelled_set_run_results.jsonl"
"""
import sys
import json
import time
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor, as_completed, TimeoutError
from conversational_txt2sql.agentic.main import run  

INPUT = "data/labelled_sets/labelled_set_processed.jsonl"
OUTPUT = "data/labelled_sets/labelled_set_run_results.jsonl"


def load_jsonl(path):
    with open(path, "r", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            yield json.loads(line)


def _call_run(instance_id, row, per_call_timeout=None):
    out = {
        "instance_id": instance_id,
        "selected_database": row.get("selected_database"),
        "user_query": row.get("user_query"),
        "generated_sql": None,
        "rows_returned": None,
        "error": None,
        "elapsed_seconds": None,
    }
    start = time.time()
    try:
        if per_call_timeout:
            # run in a thread with timeout to protect long-running calls
            from concurrent.futures import ThreadPoolExecutor as _TPE

            with _TPE(max_workers=1) as _exe:
                fut = _exe.submit(run, row.get("user_query"))
                res = fut.result(timeout=per_call_timeout)
        else:
            res = run(row.get("user_query"))

        # res is expected to be a dict: {"generated_sql": ..., "executed_df": ...}
        out["generated_sql"] = res.get("generated_sql")
        executed = res.get("executed_df")

        # normalize executed_df for json serialization
        if executed is None:
            out["rows_returned"] = 0
        else:
            try:
                # pandas.DataFrame -> records
                import pandas as _pd

                if isinstance(executed, _pd.DataFrame):
                    records = executed.to_dict(orient="records")
                    out["rows_returned"] = records
                elif isinstance(executed, list):
                    out["rows_returned"] = executed
                else:
                    # fallback: stringify small preview
                    out["rows_returned"] = None
            except Exception:
                out["rows_returned"] = None

    except TimeoutError:
        out["error"] = f"Timeout after {per_call_timeout}s"
    except Exception as e:
        out["error"] = f"{type(e).__name__}: {e}"
    finally:
        out["elapsed_seconds"] = round(time.time() - start, 3)

    return out


def main(input_path: Path = INPUT, output_path: Path = OUTPUT, workers: int = 6, per_call_timeout: int = 60):
    rows = list(load_jsonl(input_path))
    tasks = []
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with ThreadPoolExecutor(max_workers=workers) as exe, open(output_path, "w", encoding="utf-8") as outfh:
        futures = {
            exe.submit(_call_run, r.get("instance_id"), r, per_call_timeout): r.get("instance_id")
            for r in rows
        }

        for fut in as_completed(futures):
            iid = futures[fut]
            try:
                res = fut.result(timeout=per_call_timeout + 5)
            except TimeoutError:
                res = {
                    "instance_id": iid,
                    "selected_database": None,
                    "user_query": None,
                    "generated_sql": None,
                    "rows_returned": None,
                    "error": f"Overall timeout after {per_call_timeout + 5}s",
                    "elapsed_seconds": None,
                }
            except Exception as e:
                res = {
                    "instance_id": iid,
                    "selected_database": None,
                    "user_query": None,
                    "generated_sql": None,
                    "rows_returned": None,
                    "error": f"{type(e).__name__}: {e}",
                    "elapsed_seconds": None,
                }

            outfh.write(json.dumps(res, default=str) + "\n")
            outfh.flush()

    return output_path


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="Run agentic main.run for each user_query in a .jsonl and collect results.")
    parser.add_argument("-i", "--input", type=Path, default=INPUT)
    parser.add_argument("-o", "--output", type=Path, default=OUTPUT)
    parser.add_argument("-w", "--workers", type=int, default=6)
    parser.add_argument("-t", "--timeout", type=int, default=300, help="Per-call timeout (seconds)")

    args = parser.parse_args()
    out = main(input_path=args.input, output_path=args.output, workers=args.workers, per_call_timeout=args.timeout)
    print("Wrote results to", out)